package controller

// Paths and scripts inside a Kamailio pod. They share the FreeSWITCH pods' mount root.
const (
	kamailioConfigDir     = mountRoot + "/kamailio"
	kamailioConfigFile    = kamailioConfigDir + "/kamailio.cfg"
	kamailioDispatcherDir = mountRoot + "/dispatcher"
	kamailioDispatcher    = kamailioDispatcherDir + "/" + dispatcherListKey

	kamailioStartScriptName = "start.sh"
	kamailioReadyScriptName = "ready.sh"
	kamailioDrainScriptName = "drain.sh"

	// kamailioDrainMarker lives in the container's own filesystem, so a restarted container starts clean.
	kamailioDrainMarker = "/tmp/kamailio-operator-draining"
)

// kamailioStartScript is the container's command. Kamailio reads its addresses once, at start: the advertised one
// (the pod's external address, or the node's own) goes in Via and Record-Route, and JSON-RPC listens on the pod's
// own address only. When an external address is required, the pod waits for the operator to set it rather than
// start with one peers can't reach.
const kamailioStartScript = `#!/bin/sh
# Generated by freeswitch-operator. Starts Kamailio with this pod's addresses.
set -eu
file=` + externalAddrFile + `
if [ "${KAMAILIO_REQUIRE_EXTERNAL_ADDRESS:-false}" = "true" ]; then
  until [ -s "$file" ]; do
    echo "freeswitch-operator: waiting for this pod's external address"
    sleep 2
  done
fi
addr=""
[ -s "$file" ] && addr=$(cat "$file")
[ -n "$addr" ] || addr="$HOST_IP"
# A pool that gives the pod an address of its own on the node: serve peers there, FreeSWITCH on the pod's own.
bind=""
[ -s ` + bindAddrFile + ` ] && bind=$(cat ` + bindAddrFile + `)
set -- -A "PUBLIC_ADDR=$addr" -A "PRIVATE_ADDR=$POD_IP"
if [ -n "$bind" ] && [ "$bind" != "$POD_IP" ]; then
  set -- "$@" -A "BIND_ADDR=$bind"
  echo "freeswitch-operator: advertising $addr, peers on $bind, nodes and JSON-RPC on $POD_IP"
else
  echo "freeswitch-operator: advertising $addr, JSON-RPC on $POD_IP:$KAMAILIO_RPC_PORT"
fi
exec kamailio -DD -E -m "${KAMAILIO_SHM_MB:-128}" -M "${KAMAILIO_PKG_MB:-16}" "$@" -f ` + kamailioConfigFile + `
`

// kamailioReadyScript is the readiness probe: not draining, and the SIP port takes connections.
const kamailioReadyScript = `#!/bin/sh
# Generated by freeswitch-operator. Readiness for a Kamailio node.
[ -e ` + kamailioDrainMarker + ` ] && { echo "draining"; exit 1; }
# The pod's own address: it has a listener whether or not a pool gives the pod another.
nc -z -w 2 "$POD_IP" "${KAMAILIO_SIP_PORT:-5060}" || { echo "SIP port ${KAMAILIO_SIP_PORT:-5060} not answering"; exit 1; }
exit 0
`

// kamailioDrainScript runs as the preStop hook. It makes the pod unready, has Kamailio answer new calls from
// peers with 503 (they go to another Kamailio), and waits for open transactions to finish or for
// KAMAILIO_MAX_DRAIN_SECONDS to pass. Calls already up don't hold a transaction: their in-dialog requests follow the
// advertised address, which the replacement pod on that node takes over.
const kamailioDrainScript = `#!/bin/sh
# Generated by freeswitch-operator. Drains a Kamailio node before it stops.
set -u
max="${KAMAILIO_MAX_DRAIN_SECONDS:-40}"
rpc() {
  wget -q -T 3 -O - \
    --header "Authorization: Bearer $KAMAILIO_RPC_TOKEN" --header "Content-Type: application/json" \
    --post-data "{\"jsonrpc\":\"2.0\",\"method\":\"$1\",\"params\":[$2],\"id\":1}" \
    "http://$POD_IP:$KAMAILIO_RPC_PORT/RPC"
}
touch ` + kamailioDrainMarker + `
rpc pv.shvSet '"draining","int",1' >/dev/null || echo "freeswitch-operator: could not set draining; stopping on the limit"
start=$(date +%s)
while :; do
  # tm.stats answers {"current": <open transactions>, ...}
  n=$(rpc tm.stats "" 2>/dev/null | sed -n 's/.*"current"[^0-9]*\([0-9][0-9]*\).*/\1/p' | head -n 1)
  case "$n" in
    ''|*[!0-9]*) echo "freeswitch-operator: Kamailio not answering; nothing to wait for"; break ;;
  esac
  if [ "$n" -eq 0 ]; then
    echo "freeswitch-operator: no open transactions; stopping"
    break
  fi
  now=$(date +%s)
  if [ $((now - start)) -ge "$max" ]; then
    echo "freeswitch-operator: drain limit of ${max}s reached with $n transactions; stopping"
    break
  fi
  sleep 1
done
`
