// dispatcherListKey is the file name inside the dispatcher ConfigMap.
const dispatcherListKey = "dispatcher.list"

// destination is one line of a Kamailio dispatcher list.
type destination struct {
	URI  string // sip:<address>:<port>[;transport=tcp]
	Pod  string // used as the destination's duid attribute
	Node string
}

// readyDestinations turns EndpointSlices into dispatcher destinations: one per ready endpoint address. Terminating
// endpoints are never ready, so a draining node leaves the list as soon as its preStop hook starts.
func readyDestinations(endpointSlices []discoveryv1.EndpointSlice, port int32, transport string) []destination {
	seen := map[string]bool{}
	var out []destination
	for _, s := range endpointSlices {
		for _, ep := range s.Endpoints {
			if ep.Conditions.Ready == nil || !*ep.Conditions.Ready {
				continue
			}
			if ep.Conditions.Terminating != nil && *ep.Conditions.Terminating {
				continue
			}
			pod, node := "", ""
			if ep.TargetRef != nil {
				pod = ep.TargetRef.Name
			}
			if ep.NodeName != nil {
				node = *ep.NodeName
			}
			for _, addr := range ep.Addresses {
				uri := sipURI(addr, port, transport)
				if seen[uri] {
					continue
				}
				seen[uri] = true
				out = append(out, destination{URI: uri, Pod: pod, Node: node})
			}
		}
	}
	slices.SortFunc(out, func(a, b destination) int { return strings.Compare(a.URI, b.URI) })
	return out
}

func sipURI(addr string, port int32, transport string) string {
	host := net.JoinHostPort(addr, strconv.Itoa(int(port)))
	uri := "sip:" + host
	if transport != "" && transport != "udp" {
		uri += ";transport=" + transport
	}
	return uri
}

// renderDispatcherList renders a Kamailio dispatcher.list. Each line is "setid destination flags priority attrs".
// The output is deterministic so its hash changes only when membership does.
func renderDispatcherList(setID int32, dests []destination) string {
	var b strings.Builder
	b.WriteString("# Generated by freeswitch-operator from the fleet's ready endpoints. Do not edit.\n")
	b.WriteString("# setid destination flags priority attributes\n")
	for _, d := range dests {
		attrs := []string{}
		if d.Pod != "" {
			attrs = append(attrs, "duid="+d.Pod)
		}
		if d.Node != "" {
			attrs = append(attrs, "node="+d.Node)
		}
		attr := strings.Join(attrs, ";")
		if attr == "" {
			attr = "0"
		}
		fmt.Fprintf(&b, "%d %s 0 0 %s\n", setID, d.URI, attr)
	}
	return b.String()
}

// parseDispatcherURIs reads the destination URIs of the given set from a rendered list.
func parseDispatcherURIs(list string, setID int32) []string {
	var out []string
	for line := range strings.SplitSeq(list, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		if len(f) < 2 || f[0] != strconv.Itoa(int(setID)) {
			continue
		}
		out = append(out, f[1])
	}
	return out
}

// removedURIs are in old but not in new.
func removedURIs(old, cur []string) []string {
	keep := map[string]bool{}
	for _, u := range cur {
		keep[u] = true
	}
	var out []string
	for _, u := range old {
		if !keep[u] {
			out = append(out, u)
		}
	}
	return out
}

func contentHash(s string) string {
	sum := sha256.Sum256([]byte(s))
	return hex.EncodeToString(sum[:8])
}

// DispatcherNotifier tells a running Kamailio about membership changes.
type DispatcherNotifier interface {
	// SetInactive takes a destination out of rotation at once (dispatcher.set_state with "ip": inactive, probing).
	SetInactive(ctx context.Context, setID int32, uri string) error
	// Reload makes Kamailio re-read its dispatcher list from disk (dispatcher.reload), then checks that each set in
	// want now holds exactly its URIs (dispatcher.list); sets not in want aren't checked. If one doesn't, the error
	// wraps errListNotLoaded: the kubelet has not yet written the new file into that pod, and a later reload will
	// pick it up.
	Reload(ctx context.Context, want map[int32][]string) error
}

// errListNotLoaded means Kamailio reloaded but still holds another list than the one the operator wrote.
var errListNotLoaded = errors.New("kamailio has not loaded the current dispatcher list")

// NotifierFactory builds a notifier for a Kamailio JSON-RPC URL. A non-empty token is sent as a bearer token.
type NotifierFactory func(url, token string) DispatcherNotifier

// NewJSONRPCNotifier talks to Kamailio's jsonrpcs module over HTTP (xhttp).
func NewJSONRPCNotifier(url, token string) DispatcherNotifier {
	return &jsonrpcNotifier{url: url, token: token, client: &http.Client{Timeout: 5 * time.Second}}
}

type jsonrpcNotifier struct {
	url    string
	token  string
	client *http.Client
	id     atomic.Int64
}

// rpcError is an error answer from Kamailio's JSON-RPC.
type rpcError struct {
	Method  string
	Code    int    `json:"code"`
	Message string `json:"message"`
}

func (e *rpcError) Error() string {
	return fmt.Sprintf("kamailio %s: %d %s", e.Method, e.Code, e.Message)
}

func (n *jsonrpcNotifier) SetInactive(ctx context.Context, setID int32, uri string) error {
	return n.call(ctx, "dispatcher.set_state", []any{"ip", setID, uri}, nil)
}

func (n *jsonrpcNotifier) Reload(ctx context.Context, want map[int32][]string) error {
	if err := n.call(ctx, "dispatcher.reload", nil, nil); err != nil {
		// Kamailio refuses a reload within ds_reload_delta (5 s) of the last one, as when two reconciles come close
		// together. That reload read the file too: what it loaded decides, as for any other.
		var rpcErr *rpcError
		if !errors.As(err, &rpcErr) || !strings.Contains(rpcErr.Message, "Ongoing reload") {
			return err
		}
	}
	have, err := n.destinations(ctx)
	if err != nil {
		return err
	}
	ids := slices.Sorted(maps.Keys(want))
	for _, id := range ids {
		if !sameURIs(have[id], want[id]) {
			return fmt.Errorf("%w: set %d holds %v, want %v", errListNotLoaded, id, have[id], want[id])
		}
	}
	return nil
}

// destinations lists the URIs Kamailio holds, by dispatcher set (dispatcher.list).
func (n *jsonrpcNotifier) destinations(ctx context.Context) (map[int32][]string, error) {
	var res struct {
		Records []struct {
			Set struct {
				ID      int32 `json:"ID"`
				Targets []struct {
					Dest struct {
						URI string `json:"URI"`
					} `json:"DEST"`
				} `json:"TARGETS"`
			} `json:"SET"`
		} `json:"RECORDS"`
	}
	if err := n.call(ctx, "dispatcher.list", nil, &res); err != nil {
		// What Kamailio answers when it holds no sets at all, as after loading an empty list.
		if re := (*rpcError)(nil); errors.As(err, &re) && re.Message == "No Destination Sets" {
			return nil, nil
		}
		return nil, err
	}
	out := map[int32][]string{}
	for _, r := range res.Records {
		for _, t := range r.Set.Targets {
			out[r.Set.ID] = append(out[r.Set.ID], t.Dest.URI)
		}
	}
	return out, nil
}

func sameURIs(a, b []string) bool {
	a, b = slices.Clone(a), slices.Clone(b)
	slices.Sort(a)
	slices.Sort(b)
	return slices.Equal(a, b)
}

// call makes one JSON-RPC call and decodes its result into result, when that is not nil. Kamailio answers an error
// with a matching HTTP status and the error in the body, so the body is read first.
func (n *jsonrpcNotifier) call(ctx context.Context, method string, params []any, result any) error {
	req := map[string]any{"jsonrpc": "2.0", "method": method, "id": n.id.Add(1)}
	if params != nil {
		req["params"] = params
	}
	body, err := json.Marshal(req)
	if err != nil {
		return err
	}
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, n.url, bytes.NewReader(body))
	if err != nil {
		return err
	}
	httpReq.Header.Set("Content-Type", "application/json")
	if n.token != "" {
		httpReq.Header.Set("Authorization", "Bearer "+n.token)
	}
	resp, err := n.client.Do(httpReq)
	if err != nil {
		return fmt.Errorf("kamailio %s: %w", method, err)
	}
	defer func() { _ = resp.Body.Close() }()
	var out struct {
		Result json.RawMessage `json:"result"`
		Error  *rpcError       `json:"error"`
	}
	decodeErr := json.NewDecoder(resp.Body).Decode(&out)
	if decodeErr == nil && out.Error != nil {
		out.Error.Method = method
		return out.Error
	}
	if resp.StatusCode/100 != 2 {
		return fmt.Errorf("kamailio %s: HTTP %d", method, resp.StatusCode)
	}
	if decodeErr != nil {
		return fmt.Errorf("kamailio %s: decoding response: %w", method, decodeErr)
	}
	if result != nil {
		if err := json.Unmarshal(out.Result, result); err != nil {
			return fmt.Errorf("kamailio %s: decoding result: %w", method, err)
		}
	}
	return nil
}
