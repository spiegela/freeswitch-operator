package controller

// Paths inside the FreeSWITCH container. The operator mounts its scripts, the pod's downward-API annotations and
// the referenced config ConfigMaps under one root so images need no changes beyond freeswitch, fs_cli and /bin/sh.
const (
	mountRoot        = "/etc/freeswitch-operator"
	scriptsDir       = mountRoot + "/scripts"
	podInfoDir       = mountRoot + "/podinfo"
	configDir        = mountRoot + "/config"
	externalAddrFile = podInfoDir + "/external-address"
	bindAddrFile     = podInfoDir + "/bind-address"
	// failOverFile holds the pod's fail-over annotation (FailOverAnnotation), with spec.recovery: the drain reads it.
	failOverFile = podInfoDir + "/fail-over"

	// drainMarker lives in the container's own filesystem, not a volume, so a restarted container starts clean.
	drainMarker = "/tmp/freeswitch-operator-draining"

	// startupWaitSeconds bounds how long the drain waits for a FreeSWITCH that is still starting.
	startupWaitSeconds = "60"

	// recoveryWaitSeconds bounds how long the recovery on start waits for FreeSWITCH's SIP profiles: as long as
	// the startup probe gives FreeSWITCH to come up (startupGraceSeconds; a test keeps them equal).
	recoveryWaitSeconds = "120"

	// recoveredFile holds what the recovery on start did, for the exporter (freeswitch_recovery_*) and the bench.
	// It is on the pod's run volume, which outlives a container restart, so each start of FreeSWITCH removes the
	// last start's before it waits.
	recoveredFile = runDir + "/recovered"

	// fenceFile is freeswitch-fence, which an init container copies onto the run volume with spec.recovery, and
	// fenceTokenDir the projected token and CA it reads (fenceTokenVolume).
	fenceFile     = runDir + "/freeswitch-fence"
	fenceTokenDir = mountRoot + "/fence"

	drainScriptName   = "drain.sh"
	readyScriptName   = "ready.sh"
	startupScriptName = "startup.sh"
	liveScriptName    = "live.sh"
	recoverScriptName = "recover.sh"

	// shell runs the scripts; they are POSIX sh, and every FreeSWITCH image has it.
	shell = "/bin/sh"
)

// drainScript runs as the preStop hook. It makes the pod unready at once (so the dispatcher stops sending new
// calls), pauses inbound calls in FreeSWITCH (new INVITEs get 503, which Kamailio fails over on), then waits for
// live calls to finish or for FS_MAX_DRAIN_SECONDS to pass. The kubelet sends SIGTERM when it returns.
//
// With spec.recovery, a member a person fails over (the fail-over annotation) keeps its calls instead: the drain
// stops FreeSWITCH at once without hanging them up (fsctl crash), and the replacement, starting on another node with
// this pod's address, recovers them (recoverScript). A clean stop would hang them up, deleting what recovery reads.
// The kubelet doesn't restart a container in a pod being deleted, so FreeSWITCH can't come back here and take them.
// The annotation comes from a downward-API file only a fleet with spec.recovery has (failOverFile). The kubelet
// refreshes it within a second or so of a change, and the failover's delete can follow the annotation that closely,
// so the drain looks for up to two seconds.
//
// With spec.recovery it first asks whether the operator failed the pod over automatically (freeswitch-fence, from
// fenceFile): such a pod is deleted at once, as its node is lost, and if the node comes back its kubelet stops the
// pod, giving this hook a second. Its calls are the replacement's by then, recovered on the spare, and a clean stop
// would hang them up there with a BYE. So when the API server refuses the pod's own token, which it does once the
// pod is gone and never through a graceful delete, the drain stops FreeSWITCH at once without hanging up. Anything
// else (the pod still there, the API server not answering within its 600 ms) drains as usual.
const drainScript = `#!/bin/sh
# Generated by freeswitch-operator. Drains a FreeSWITCH node before it stops.
set -u
max="${FS_MAX_DRAIN_SECONDS:-7200}"
cli() { fs_cli -T 2000 -t 5000 "$@"; }
fence="${FS_FENCE:-` + fenceFile + `}"
if [ -x "$fence" ] && "$fence" check -token "${FS_FENCE_TOKEN_DIR:-` + fenceTokenDir + `}/token" -ca "${FS_FENCE_TOKEN_DIR:-` + fenceTokenDir + `}/ca.crt"; then
  { echo "freeswitch-operator: this pod was failed over (its token is refused: the pod is gone); stopping FreeSWITCH without hanging up its calls, which its replacement recovers" >> "${FS_DRAIN_LOG:-/proc/1/fd/1}"; } 2>/dev/null || true
  cli -x "fsctl crash" >/dev/null 2>&1
  exit 0
fi
touch ` + drainMarker + `
# FreeSWITCH loses a SIGTERM that arrives while it is still starting, and the pod would then wait out its whole
# grace period (maxDrainSeconds). So when the pod is stopped just after it started, let FreeSWITCH finish
# starting first; the kubelet's SIGTERM after this script then stops it.
waited=0
until cli -x "status" 2>/dev/null | grep -q "is ready"; do
  if [ "$waited" -ge ` + startupWaitSeconds + ` ]; then
    echo "freeswitch-operator: FreeSWITCH not ready after ${waited}s; stopping anyway"
    break
  fi
  sleep 1
  waited=$((waited + 1))
done
failover="${FS_FAIL_OVER_FILE:-` + failOverFile + `}"
if [ -e "$failover" ]; then
  looked=0
  while :; do
    if [ "$(cat "$failover" 2>/dev/null)" = true ]; then
      { echo "freeswitch-operator: failed over by hand; stopping FreeSWITCH without hanging up its calls, for its replacement on another node to recover" >> "${FS_DRAIN_LOG:-/proc/1/fd/1}"; } 2>/dev/null || true
      cli -x "fsctl crash" >/dev/null 2>&1
      exit 0
    fi
    [ "$looked" -ge 2 ] && break
    sleep 1
    looked=$((looked + 1))
  done
fi
cli -x "fsctl pause inbound" >/dev/null 2>&1 || true
start=$(date +%s)
missed=0
while :; do
  # FreeSWITCH's own count of the call legs it holds: status prints "<n> session(s) - peak ...". Not "show calls
  # count", which reads the core db: with the core db in a database, a statement the database refuses (a caller
  # name too long for its column) rolls back the others batched with it, the deletes of ended calls among them,
  # and a node would wait out the whole drain limit for calls long gone.
  n=$(cli -x "status" 2>/dev/null | awk '/session\(s\) - peak/ {print $1; exit}')
  case "$n" in
    ''|*[!0-9]*)
      # One slow answer at peak is no reason to hang up every call: give up only after 5 misses in a row.
      missed=$((missed + 1))
      if [ "$missed" -ge 5 ]; then
        echo "freeswitch-operator: FreeSWITCH not answering; nothing to wait for"
        break
      fi
      sleep 2
      continue ;;
  esac
  missed=0
  if [ "$n" -eq 0 ]; then
    echo "freeswitch-operator: no live calls; stopping"
    break
  fi
  now=$(date +%s)
  if [ $((now - start)) -ge "$max" ]; then
    echo "freeswitch-operator: drain limit of ${max}s reached with $n call legs; stopping"
    break
  fi
  sleep 2
done
`

// startupScript is the startup probe, and the part of readiness about FreeSWITCH itself: it is ready, and a SIP
// profile is running on FS_SIP_PORT, the port Kamailio sends calls to. FreeSWITCH reports ready with no profile at
// all (a profile that failed to load, an empty sip_profiles), and a node like that must never take calls or let a
// roll move on. Until this passes the pod has never been ready, so it holds no calls and the kubelet's restart
// after too many failures loses nothing.
//
// Readiness fails on one failed check, so a drain takes the pod out at once; a check is retried once instead, so one
// slow or lost fs_cli answer doesn't. At most three fs_cli calls of 1.5 s fit in probeTimeoutSeconds.
const startupScript = `#!/bin/sh
# Generated by freeswitch-operator. FreeSWITCH is up and listening for SIP on FS_SIP_PORT.
port="${FS_SIP_PORT:-5060}"
cli() { fs_cli -T 300 -t 1200 -x "$1" 2>/dev/null; }
ready() { cli "status" | grep -q "is ready"; }
# "sofia status" lines: <name> profile sip:mod_sofia@<ip>:<port> RUNNING (<n>)
listening() {
  cli "sofia status" \
    | awk -v suffix=":$port" '$2 == "profile" && $4 == "RUNNING" && substr($3, length($3) - length(suffix) + 1) == suffix {found = 1} END {exit !found}'
}
retries=1
until ready; do
  [ "$retries" -gt 0 ] || { echo "FreeSWITCH is not ready"; exit 1; }
  retries=$((retries - 1))
done
until listening; do
  [ "$retries" -gt 0 ] || { echo "no SIP profile running on port $port"; exit 1; }
  retries=$((retries - 1))
done
exit 0
`

// liveScript is the liveness probe, used only when spec.liveness is set. It fails only when FreeSWITCH doesn't
// answer at all: not ready, paused and draining all count as alive, since a restart would drop the node's calls.
// fs_cli's command timeout stays two seconds under the probe's, so a slow answer is a failed check the script
// reports rather than a probe the kubelet kills.
const liveScript = `#!/bin/sh
# Generated by freeswitch-operator. Liveness: FreeSWITCH answers fs_cli.
t="${FS_LIVENESS_TIMEOUT_SECONDS:-15}"
ms=$(( (t > 4 ? t - 2 : 2) * 1000 ))
fs_cli -T 3000 -t "$ms" -x "status" 2>/dev/null | grep -q "^UP " && exit 0
echo "FreeSWITCH did not answer fs_cli within $((ms / 1000))s"
exit 1
`

// readyScript is the readiness probe. A pod is ready only when it is not draining, knows its external address
// (when required), and passes the startup checks again: a profile that stops later takes the node out of the
// dispatcher list without touching its calls. Readiness is what puts a pod into the dispatcher list.
const readyScript = `#!/bin/sh
# Generated by freeswitch-operator. Readiness for a FreeSWITCH node.
[ -e ` + drainMarker + ` ] && { echo "draining"; exit 1; }
if [ "${FS_REQUIRE_EXTERNAL_ADDRESS:-false}" = "true" ]; then
  [ -s ` + externalAddrFile + ` ] || { echo "no external address yet"; exit 1; }
fi
exec /bin/sh "$(dirname "$0")/` + startupScriptName + `"
`

// addressWaitScript runs as an init container in a fleet that draws from a SIPAddressPool: it returns once the
// downward-API file holds the pod's external address, which the kubelet refreshes in place when the operator sets
// the annotation (within seconds, checked on kind).
const addressWaitScript = `f="${FS_EXTERNAL_ADDRESS_FILE}"
n=0
until [ -s "$f" ]; do
  [ $((n % 30)) -eq 0 ] && echo "freeswitch-operator: waiting for this pod's external address"
  n=$((n + 1))
  sleep 1
done
echo "freeswitch-operator: external address $(cat "$f")"
`

// recoverScript runs as the postStart hook when spec.recovery is set. The kubelet runs no probe until it returns,
// so the pod turns ready only after the calls tracked under its address are back. It waits for every SIP profile
// in FreeSWITCH's sofia.conf to run (a bridged call is recovered only with both legs, and profiles start one by
// one), checks each is named for the pod's address (NAME-<address>, as bin/profile-name.sh names them: a profile
// under a name every node shares would take other nodes' calls), and runs `sofia recover`. Whatever happens it
// exits 0: a failed postStart hook kills the container, and FreeSWITCH restarting would not recover the calls
// either. What it did goes to the container's log and to the recovered file, one line.
const recoverScript = `#!/bin/sh
# Generated by freeswitch-operator. Recovers the calls tracked under this pod's address once FreeSWITCH is up.
set -u
max="${FS_RECOVERY_WAIT_SECONDS:-` + recoveryWaitSeconds + `}"
file="${FS_RECOVERED_FILE:-` + recoveredFile + `}"
rm -f "$file"
# A postStart hook's output is dropped unless it fails, so the result goes to FreeSWITCH's own (the container's log).
log="${FS_RECOVERY_LOG:-/proc/1/fd/1}"
done_() {
  echo "$1" > "$file.tmp" && mv "$file.tmp" "$file"
  { echo "freeswitch-operator: recovery: $1" >> "$log"; } 2>/dev/null || true
  exit 0
}
cli() { fs_cli -T 2000 -t "$1" -x "$2" 2>/dev/null; }
addr=$(tr -d ' \t\r\n' < "${FS_EXTERNAL_ADDRESS_FILE:-` + externalAddrFile + `}" 2>/dev/null | sed 's/[^A-Za-z0-9]/-/g')
[ -n "$addr" ] || done_ "skipped: this pod has no external address"
waited=0
while :; do
  if cli 5000 "status" | grep -q "is ready"; then
    want=$(cli 5000 "xml_locate configuration configuration name sofia.conf" \
      | sed -n 's/.*<profile[[:space:]][[:space:]]*name="\([^"]*\)".*/\1/p' | sort -u)
    running=$(cli 5000 "sofia status" | awk '$2 == "profile" && $4 == "RUNNING" {print $1}' | sort -u)
    missing=""
    for p in $want; do
      echo "$running" | grep -qxF "$p" || missing="$missing $p"
    done
    [ -n "$want" ] && [ -z "$missing" ] && break
  fi
  if [ "$waited" -ge "$max" ]; then
    why="${missing:+missing$missing}"
    done_ "skipped: SIP profiles not all running after ${waited}s (${why:-FreeSWITCH not ready}); calls not recovered"
  fi
  sleep 1
  waited=$((waited + 1))
done
for p in $want; do
  case "$p" in
    *-"$addr") ;;
    *) done_ "skipped: SIP profile $p is not named for this pod's address (NAME-$addr); calls not recovered" ;;
  esac
done
out=$(cli 60000 "sofia recover" | tr -s ' \r\n' ' ' | sed 's/ *$//')
done_ "${out:-no answer from sofia recover}"
`
